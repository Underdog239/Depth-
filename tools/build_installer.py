#!/usr/bin/env python3
"""Bundle a Rojo .rbxlx into a standalone Roblox Studio Command Bar installer."""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
from build_runtime import bundle as runtime_bundle


def literal(value):
    delimiter = '='
    while ']' + delimiter + ']' in value:
        delimiter += '='
    # Luau strips exactly the first newline after a long-string opener.
    return '[' + delimiter + '[\n' + value + ']' + delimiter + ']'


def bundle(place):
    root = ET.parse(place).getroot()
    nodes = []
    destinations = []

    def add(item, parent):
        properties = item.find('Properties')
        name = properties.find("*[@name='Name']").text
        class_name = item.attrib['class']
        if class_name not in {'Folder', 'ModuleScript', 'LocalScript'}:
            raise ValueError('Unsupported instance: ' + class_name)
        for prop in properties:
            if prop.attrib['name'] not in {'Name', 'Source'}:
                raise ValueError('Unsupported property: ' + prop.attrib['name'])
        source = properties.find("*[@name='Source']")
        index = len(nodes) + 1
        nodes.append('{class = %s, name = %s, parent = %d%s}' % (
            literal(class_name), literal(name), parent,
            ', source = ' + literal(source.text or '') if source is not None else ''))
        for child in item.findall('Item'):
            add(child, index)
        return index

    for service in root.findall('Item'):
        service_name = service.attrib['class']
        if service_name == 'StarterPlayer':
            container = service.find("Item[@class='StarterPlayerScripts']")
            if container is None or len(service.findall('Item')) != 1:
                raise ValueError('Unexpected StarterPlayer layout')
            destination = 'starterScripts'
        elif service_name == 'ReplicatedStorage':
            container = service
            destination = 'game:GetService(' + literal(service_name) + ')'
        else:
            raise ValueError('Unsupported service: ' + service_name)
        for child in container.findall('Item'):
            destinations.append('{index = %d, parent = %s}' % (add(child, 0), destination))

    runtime = runtime_bundle(place)
    return '''-- Generated by tools/build_installer.py; edit src/ and rebuild instead.
-- Edit mode: install in Studio Command Bar. Running client: start the bundled runtime.
-- Installs only into empty target paths; existing content is never overwritten.
local runService = game:GetService("RunService")
if runService:IsRunning() then
    assert(runService:IsClient(), "Depth needs client execution. Use a LocalScript; server execution is unsupported.")
    local function startRuntime()
''' + runtime + '''
    end
    return startRuntime()
end
assert(runService:IsStudio(),
    "Depth installation needs Studio Edit mode; the runtime needs a running Roblox client.")
local starterScripts = game:GetService("StarterPlayer"):FindFirstChildOfClass("StarterPlayerScripts")
assert(starterScripts, "Depth installer: StarterPlayerScripts is missing.")
local definitions = {
''' + ',\n'.join(nodes) + '''
}
local destinations = {
''' + ',\n'.join(destinations) + '''
}
-- Preflight every destination before creating or parenting anything.
for _, destination in ipairs(destinations) do
    local name = definitions[destination.index].name
    assert(not destination.parent:FindFirstChild(name),
        "Depth installer: " .. destination.parent:GetFullName() .. "." .. name
        .. " already exists. Use a new Baseplate or move that object first.")
end
local created = {}
local ok, failure = pcall(function()
    -- Assemble all scripts off-tree, including their sources and children.
    for index, definition in ipairs(definitions) do
        local object = Instance.new(definition.class)
        created[index] = object
        object.Name = definition.name
        if definition.source then object.Source = definition.source end
        if definition.parent ~= 0 then object.Parent = created[definition.parent] end
    end
    for _, destination in ipairs(destinations) do
        created[destination.index].Parent = destination.parent
    end
end)
if not ok then
    for _, object in ipairs(created) do object:Destroy() end
    error("Depth installation failed: " .. tostring(failure), 0)
end
print("Depth installed. Press Play, then Run demo. Save the place to keep it.")
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('place')
    parser.add_argument('output')
    args = parser.parse_args()
    Path(args.output).write_text(bundle(args.place), encoding='utf-8')
