#!/usr/bin/env python3
"""Bundle a Rojo place's client modules as ordinary Luau functions (no Source writes)."""
import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

REQUIRE = re.compile(r'require\((script|ReplicatedStorage|game:GetService\("ReplicatedStorage"\))((?:\.[A-Za-z0-9_]+)+)\)')


def compile_modules(place):
    root = ET.parse(place).getroot()
    nodes, sources, parents = {}, {}, {}

    def visit(item, parent=''):
        name = item.findtext("./Properties/*[@name='Name']")
        path = parent + '/' + name if parent else name
        nodes[path] = item.attrib['class']
        parents[path] = parent
        source = item.find("./Properties/*[@name='Source']")
        if source is not None:
            sources[path] = source.text or ''
        for child in item.findall('Item'):
            visit(child, path)
    for child in root.findall('Item'):
        visit(child)
    entries = [path for path in sources if nodes[path] == 'LocalScript']
    if len(entries) != 1 or any(kind == 'Script' for kind in nodes.values()):
        raise ValueError('Expected one client bootstrap and no server scripts')
    edges = {}
    rewritten = {}
    for path, source in sources.items():
        # ROM data is supplied through normal Assets.ROM or the in-game paste UI.
        if path.startswith('ReplicatedStorage/Assets/'):
            continue
        edges[path] = []

        def replace(match):
            target = path if match.group(1) == 'script' else 'ReplicatedStorage'
            for segment in match.group(2).split('.')[1:]:
                target = parents.get(target, '') if segment == 'Parent' else target + '/' + segment
            if nodes.get(target) != 'ModuleScript':
                raise ValueError('Unresolved module: ' + match.group(0) + ' in ' + path)
            edges[path].append(target)
            return '__load(' + json.dumps(target) + ')'
        source = REQUIRE.sub(replace, source)
        # Exports are local to each module factory in the bundle.
        source = re.sub(r'^export type ', 'type ', source, flags=re.M)
        rewritten[path] = source
    for origin, targets in edges.items():
        for target in targets:
            if target not in rewritten:
                raise ValueError('Dependency is excluded from runtime bundle: ' + target)
    return rewritten, entries[0], edges


def bundle(place, *, launch=True):
    modules, entry, edges = compile_modules(place)
    output = ['''-- Generated by tools/build_runtime.py. Roblox client runtime; no Studio installation required.
-- Paste this complete file into one LocalScript in StarterPlayerScripts in your own experience.
-- Requires Roblox client APIs; HTTP/loadstring support is not added by this file.
local __factories, __cache, __loading = {}, {}, {}
local function __load(name)
    if __cache[name] ~= nil then return __cache[name] end
    assert(not __loading[name], "Circular Depth module: " .. name)
    local factory = assert(__factories[name], "Missing Depth module: " .. name)
    __loading[name] = true
    local ok, result = pcall(factory)
    __loading[name] = nil
    if not ok then error(result, 0) end
    assert(result ~= nil, "Depth module returned nil: " .. name)
    __cache[name] = result
    return result
end
''']
    for path, source in modules.items():
        output.append('__factories[' + json.dumps(path) + '] = function()\n'
                      '-- Bundled modules have no individual script Instances. Source reports are prebuilt.\n'
                      'local script = nil\n' + source + '\nend\n')
    if launch:
        output.append('''-- Check required capabilities, not Studio or execution-mode flags.
local __player = assert(game:GetService("Players").LocalPlayer,
    "Depth needs Players.LocalPlayer. Run this in a Roblox player client.")
local __gui = assert(__player:WaitForChild("PlayerGui", 10),
    "Depth could not find PlayerGui after 10 seconds. Wait for the player to finish loading and retry.")
if __gui:FindFirstChild("LuauGBA") then
    warn("Depth is already running for this player; keeping the existing session.")
    return
end
''')
        # Bootstrap returns no value, unlike the cached modules.
        output.append('__factories[' + json.dumps(entry) + ']()\n')
    else:
        output.append('return {load = __load, factories = __factories}\n')
    return '\n'.join(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('place')
    parser.add_argument('output')
    args = parser.parse_args()
    Path(args.output).write_text(bundle(args.place), encoding='utf-8')
