#!/usr/bin/env python3
"""Deterministic source heuristics; findings need review, not automatic rewriting."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def scan():
    findings = []
    digest = hashlib.sha256()
    for path in sorted((ROOT / 'src').rglob('*.luau')):
        if path.name == 'BuildReport.luau':
            continue
        relative = path.relative_to(ROOT).as_posix()
        source = path.read_text()
        digest.update(relative.encode() + b'\0' + source.encode() + b'\0')
        for number, line in enumerate(source.splitlines(), 1):
            # Only suspicious calls, not strings describing detector rules.
            if re.search(r'^\s*(?:local\s+\w+\s*=\s*)?(?:loadstring|[gs]etfenv)\s*\(', line) or re.search(r'require\s*\(\s*\d+', line):
                findings.append(dict(category='vulnerability', severity='warn', source=relative,
                                     line=number, message='Dynamic code or numeric asset require: review trust boundary'))
            if re.search(r'--\s*(?:TODO|FIXME|HACK|XXX)\b', line):
                findings.append(dict(category='unfinished', severity='info', source=relative,
                                     line=number, message=line.strip()[:180]))
            if re.search(r':\s*(?:InvokeServer|FireServer|GetDataStore)\s*\(', line):
                findings.append(dict(category='vulnerability', severity='error', source=relative,
                                     line=number, message='Server dependency in client-only build'))
    # Explicit capability gaps cannot be inferred reliably by token scanning.
    findings.extend([
        dict(category='unfinished', severity='warn', source='src/Client/Audio/init.luau', line=1,
             message='Full PCM audio unavailable on public Roblox clients; uploaded square-wave adapter is approximate'),
        dict(category='unfinished', severity='info', source='src/Client/Emulator/Cart/HLEBIOS.luau', line=1,
             message='BIOS emulation is partial; unsupported SWIs stop with a diagnostic'),
        dict(category='unfinished', severity='info', source='docs/TESTING.md', line=1,
             message='Studio device, controller, audio permission and real game compatibility checks are still required'),
    ])
    return dict(sourceHash=digest.hexdigest(), findings=findings)


def module(report):
    def quote(text):
        return json.dumps(text, ensure_ascii=False)
    entries = []
    for finding in report['findings']:
        entries.append('{ ' + ', '.join(key+' = '+(str(value) if isinstance(value,int) else quote(value))
                                       for key,value in finding.items()) + ' }')
    return '-- Generated by tools/scan_health.py; source findings are heuristics, not a security audit.\nreturn { sourceHash = '+quote(report['sourceHash'])+', findings = {\n'+',\n'.join(entries)+'\n} }\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True)
    parser.add_argument('--module')
    args = parser.parse_args()
    report = scan()
    output = Path(args.output); output.mkdir(parents=True, exist_ok=True)
    (output/'health.json').write_text(json.dumps(report, indent=2)+'\n')
    lines = ['# Depth source health report', '', 'Source SHA256: `'+report['sourceHash']+'`', '',
             'Heuristic source findings and known limits. Tests report runtime correctness separately. No source code is automatically patched.', '']
    for f in report['findings']:
        lines.append('- **'+f['category']+' / '+f['severity']+'** — `'+f['source']+':'+str(f['line'])+'`: '+f['message'].replace('<','&lt;'))
    (output/'health.md').write_text('\n'.join(lines)+'\n')
    if args.module: Path(args.module).write_text(module(report))
    print(f"Source scan: {len(report['findings'])} findings (includes known limitations)")
    if any(f['severity']=='error' for f in report['findings']): raise SystemExit(1)

if __name__ == '__main__': main()
